// Writes app/lib/abi/{pool,lens,external,game}.ts from the forge artifacts under ../out.
// Run `forge build` at the repo root first, then `npm run abi`.
//
// The names follow the original Draw Shapes app so its components port unchanged: `fwaCloneAbi` is
// DrawEngine (the protocol-owned fork of FWA's custom pool), `poolAbi` is DrawController (settles,
// books captures and restocks the board), `lensAbi` is the Base Lens.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outDir = join(root, "site", "app", "lib", "abi");
mkdirSync(outDir, { recursive: true });

const abiOf = (file, name = file) => JSON.parse(readFileSync(join(root, "out", `${file}.sol`, `${name}.json`), "utf8")).abi;
const keep = (abi, names) => abi.filter((e) => (e.type === "function" || e.type === "event" || e.type === "error") && (!names || names.includes(e.name)));

// One ABI entry per line keeps the generated files short and diffable.
const block = (constName, abi, source) =>
  `// From ${source}.\nexport const ${constName} = [\n${abi.map((e) => `  ${JSON.stringify(e)},`).join("\n")}\n] as const;\n`;
const emit = (file, parts) => {
  writeFileSync(join(outDir, file), `// Generated by site/scripts/abi.mjs. Run \`npm run abi\` to refresh.\n${parts.join("\n")}`);
  console.log(`${file}: written`);
};

emit("pool.ts", [block("poolAbi", keep(abiOf("DrawController")), "out/DrawController.sol/DrawController.json")]);
emit("lens.ts", [block("lensAbi", keep(abiOf("Lens")), "out/Lens.sol/Lens.json")]);
emit("game.ts", [
  block("vaultAbi", keep(abiOf("GrailVault")), "out/GrailVault.sol/GrailVault.json"),
  block("farmAbi", keep(abiOf("GenesisFarm")), "out/GenesisFarm.sol/GenesisFarm.json"),
  block("tokenAbi", keep(abiOf("EngineToken"), ["balanceOf", "totalSupply", "symbol"]), "out/EngineToken.sol/EngineToken.json"),
]);
emit("external.ts", [
  block("fwaCloneAbi", keep(abiOf("DrawEngine")), "out/DrawEngine.sol/DrawEngine.json"),
  block("shapesAbi", keep(abiOf("Shapes"), ["balanceOf", "ownerOf", "backingOf", "valueOf", "redeem", "tokenURI", "isApprovedForAll", "setApprovalForAll"]), "out/Shapes.sol/Shapes.json"),
  block("packsAbi", keep(abiOf("ShapePacks"), ["ownerOf", "valueOf", "contentsOf", "redeem", "tokenURI"]), "out/ShapePacks.sol/ShapePacks.json"),
]);
