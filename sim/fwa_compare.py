#!/usr/bin/env python3
"""Draw Shapes on Base vs. the same protocol-owned design as an FWA V2 custom pool on Ethereum.

Both run the Base launch settings through the 14-day model of sim/followup.py: the 100-item reference
board, fee split 3.5 / 0.5 / 3 (premium / maintenance / GRAIL feed), 2.2 ETH pool, 0.5 ETH reserve,
GRAIL ladder 0.5 / 1 / 5 ETH listed at 80 % decaying to 50 %, treasury policy, and ENGINE trading fees
(1.75 % of volume to the treasury). Depositors are replaced by the protocol-owned pool on both.

What differs (FWAClone, verified source; factory state read on Ethereum 2026-10-26):
  - price: Base fee x 1.01 (settlement fee) + purchaser VRF fee; FWA fee x 1.05 (factory edge 500 bps)
  - pool receives: Base the fee; FWA fee x 1.025 (half the edge; FWA keeps the other half)
  - VRF: Base purchaser-paid (0.01 gwei basefee); FWA's service pays the oracle (request fee 0)
  - keeper gas: Base 0.01 gwei; Ethereum 0.05 gwei (0.042 read live) and a 1 gwei stress case
Not modelled: FWA's inventory-change cooldown and per-transaction caps, the referral program (FWAClone
has none), an edge change by the factory owner, and Draw Packs (not yet deployed on Ethereum).
Writes sim/results/fwa-compare.md. Usage: python3 sim/fwa_compare.py [seeds]
"""
import os, sys

sys.path.insert(0, os.path.dirname(__file__))
from followup import run, med  # noqa: E402,F401

LAUNCH = ("launch 3.5/0.5/3", 350, 50, 300, 2500, True, True)
BASE = dict(name="base", price=1.01, pool=1.0, own_vrf=True)
FWA = dict(name="fwa", price=1.05, pool=1.025, own_vrf=False)
CASES = [("Base", BASE, 0.01), ("FWA, Ethereum 0.05 gwei", FWA, 0.05), ("FWA, Ethereum 1 gwei", FWA, 1.0)]


def main():
    seeds = int(sys.argv[1]) if len(sys.argv) > 1 else 200
    lines = ["# Base vs. FWA custom pool with the ENGINE model (generated by sim/fwa_compare.py)\n",
             f"Medians over {seeds} seeds, 14 days, Base launch settings on both (see the module docstring). "
             "`return` is ETH backing won / ETH paid, GRAIL wins included. `surplus` is the buyback budget at "
             "genesis end (NAV above 2.2 ETH, from free cash). `platform` is the settlement fee (Base) or FWA's "
             "half of the edge. `keeper unpaid` is gas the maintenance bucket could not refund.\n",
             "| pulls/day | trading ETH/day | platform | pulls | price/pull | return | GRAILs minted | hours without GRAIL "
             "| GRAIL feed | treasury to GRAIL | surplus | platform | keeper unpaid |", "|" + "---|" * 13]
    for pulls in (100, 300, 750):
        for vol in (0.0, 1.0, 3.0):
            for name, plat, gas in CASES:
                r = run(LAUNCH, pulls, vol, gas, seeds, platform=plat)
                lines.append(f"| {pulls} | {vol:g} | {name} | {r['pulls']:.0f} | {r['paid'] / max(r['pulls'], 1):.5f} | "
                             f"{100 * r['rtp_total']:.1f} % | {r['grails']:.0f} | {r['no_grail_h']:.0f} | {r['feed']:.3f} | "
                             f"{r['grail_trading']:.3f} | {r['surplus']:.3f} | {r['platform_take']:.3f} | "
                             f"{r['keeper_unpaid_mean']:.4f} |")
                print(lines[-1], flush=True)
    out = os.path.join(os.path.dirname(__file__), "results", "fwa-compare.md")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
