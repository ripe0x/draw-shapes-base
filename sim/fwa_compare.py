#!/usr/bin/env python3
"""Draw Shapes on Base vs. the same protocol-owned ENGINE design as an FWA V2 custom pool on Ethereum.

All variants run the Base launch settings through the 14-day model of sim/followup.py: the 100-item
reference board, fee split 3.5 / 0.5 / 3 (premium / maintenance / GRAIL feed), 2.2 ETH pool, 0.5 ETH
reserve, GRAIL ladder 0.5 / 1 / 5 ETH listed at 80 % decaying to 50 %, treasury policy (reserve, then
GRAIL first while none is live, else 90 % GRAIL / 10 % POL), surplus buyback at genesis end, and ENGINE
trading fees (2 % hook fee: 1.75 % of volume to the treasury, 0.25 % to the operator). Depositors are
replaced by the protocol-owned pool everywhere.

Variants:
  - Base: DrawEngine. Price = fee x 1.01 + purchaser VRF fee; the 1 % settlement fee goes 50 % referrer
    (development without one) / 25 % Token Works / 25 % development; development also keeps the VRF
    service margin (30 % of the per-pull gas cost, about 0.0000037 ETH a pull at 0.01 gwei).
  - FWA: FWAClone as is (factory read 2026-10-26: edge 500 bps, VRF request fee 0). Price = fee x 1.05;
    the pool owner receives fee x 1.025, FWA 0.025. No settlement fee, no referrals.
  - FWA + our fee: our purchase-operator contract in front of the FWA pool also charges the Base 1 %
    settlement fee with the same split. Price = fee x 1.06.
Keeper gas: Base 0.01 gwei, Ethereum 0.05 gwei (0.042 read live); a 1 gwei stress row shows the gas the
maintenance bucket cannot refund on Ethereum.
Not modelled: FWA's inventory-change cooldown and per-transaction caps, a factory edge change, Draw
Packs on Ethereum (not deployed yet), post-genesis trading.
Writes sim/results/fwa-compare.md. Usage: python3 sim/fwa_compare.py [seeds]
"""
import os, sys

sys.path.insert(0, os.path.dirname(__file__))
from followup import run  # noqa: E402

LAUNCH = ("launch 3.5/0.5/3", 350, 50, 300, 2500, True, True)
VARIANTS = [
    ("Base", dict(name="base", edge=0.0, settle=0.01, own_vrf=True), 0.01),
    ("FWA", dict(name="fwa", edge=0.05, settle=0.0, own_vrf=False), 0.05),
    ("FWA + our fee", dict(name="fwa+fee", edge=0.05, settle=0.01, own_vrf=False), 0.05),
]
VRF_MARGIN_PER_PULL = 1_250_000 * 0.01e-9 * 0.3  # development's VRF service margin on Base at 0.01 gwei
HOOK_FEE, OPERATOR_SHARE = 0.02, 0.0025 / 0.02
SCENARIOS = [(100, 0.0), (300, 1.0), (750, 3.0)]


def flows(r, vol, label):
    """14-day flows (median run) in ETH."""
    pulls = r["pulls"]
    trading_fees = vol * 14 * HOOK_FEE
    settle = r["settle_take"]
    vrf_margin = pulls * VRF_MARGIN_PER_PULL if label == "Base" else 0.0
    dev = settle * 0.25 + vrf_margin
    operator = trading_fees * OPERATOR_SHARE
    return {
        "Pulls": f"{pulls:.0f}",
        "Price per pull": f"{r['paid'] / max(pulls, 1):.5f}",
        "Player return (GRAIL wins included)": f"{100 * r['rtp_total']:.1f} %",
        "Players paid": f"{r['paid']:.3f}",
        "Players won (ETH in prizes)": f"{r['won']:.3f}",
        "GRAILs minted": f"{r['grails']:.0f}",
        "Hours with no GRAIL": f"{r['no_grail_h']:.0f}",
        "GRAIL fund from gameplay (feed)": f"{r['feed']:.3f}",
        "GRAIL fund from ENGINE trading": f"{r['grail_trading']:.3f}",
        "Protocol liquidity added (POL)": f"{r['pol']:.3f}",
        "Buyback budget at genesis end": f"{r['buyback']:.3f}",
        "Keeper gas refunded": f"{r['keeper']:.4f}",
        "ENGINE trading fees (2 %)": f"{trading_fees:.3f}",
        "  of which to you (operator, 0.25 %)": f"{operator:.3f}",
        "Shapes mint fees (creator)": f"{r['mint_fees']:.3f}",
        "Settlement fee: referrers (50 %)": f"{settle * 0.5:.3f}",
        "Settlement fee: Token Works (25 %)": f"{settle * 0.25:.3f}",
        "Settlement fee: you (25 %) + VRF margin": f"{dev:.3f}",
        "FWA (half the edge)": f"{r['fwa_take']:.3f}",
        "You in total (excl. mint fees)": f"{dev + operator:.3f}",
    }


def main():
    seeds = int(sys.argv[1]) if len(sys.argv) > 1 else 200
    lines = ["# Base vs. FWA custom pool, ENGINE model on both (generated by sim/fwa_compare.py)\n",
             f"Medians over {seeds} seeds, 14 days of genesis, Base launch settings on every variant (see the module "
             "docstring). ETH unless marked. Medians are taken per row, so rows need not add up exactly.\n"]
    for pulls, vol in SCENARIOS:
        results = []
        for label, plat, gas in VARIANTS:
            results.append((label, flows(run(LAUNCH, pulls, vol, gas, seeds, platform=plat), vol, label)))
        lines += [f"## {pulls} pulls/day, {vol:g} ETH/day of ENGINE trading\n",
                  "| | " + " | ".join(l for l, _ in results) + " |", "|---|" + "---|" * len(results)]
        for key in results[0][1]:
            lines.append(f"| {key} | " + " | ".join(f[key] for _, f in results) + " |")
        stress = run(LAUNCH, pulls, vol, 1.0, seeds, platform=VARIANTS[2][1])
        lines += ["", f"Ethereum at 1 gwei: keeper gas the maintenance bucket cannot refund over 14 days "
                      f"(mean) {stress['keeper_unpaid_mean']:.3f} ETH.\n"]
        print("\n".join(lines[-len(results[0][1]) - 4:]), flush=True)
    out = os.path.join(os.path.dirname(__file__), "results", "fwa-compare.md")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
