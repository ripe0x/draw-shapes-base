#!/usr/bin/env python3
"""Best player outcome for the ENGINE game on an FWA V2 custom pool (Ethereum), operator keeping only the
Shapes mint fee and 0.25 % of ENGINE trading.

Fixed by FWA: price = board EV x 1.05; the pool receives EV x 1.025; FWA's VRF service pays the oracle.
Our levers: list-price markup over backing (negative = below cost, a subsidy), where the pool's margin
goes (keeper / GRAIL / premium for buybacks), and the 3 % trading fee (2.75 % to the treasury: reserve,
then the GRAIL fund). No settlement fee, no VRF margin. Board, GRAIL ladder and policy as on Base.
Rows:
  - reference: FWA with the Base launch settings (markup 7 % = 3.5 / 0.5 / 3) and a 2 % trading fee
  - lean: list at backing + mint fee; the pool's margin (its half of the edge) 10 % keeper / 90 % GRAIL
  - below cost 1 % / 2.5 %: lean, listed under backing + mint fee; trading fees and the half-edge pay for it
14 days, 300 pulls/day, Ethereum keeper gas 0.05 gwei. `NAV change` is the ordinary pool's value at day 14
minus the 2.2 ETH it started with (negative = the subsidy is eating capital); `backstop` is reserve ETH the
treasury moved into the pool. `farm pulls/day`: sim/farming.py equilibrium (25M, 0.7 ETH/day outside buying).
Writes sim/results/fwa-best.md. Usage: python3 sim/fwa_best.py [seeds]
"""
import os, sys

sys.path.insert(0, os.path.dirname(__file__))
import farming  # noqa: E402
from followup import run  # noqa: E402

FWA = dict(name="fwa", edge=0.05, settle=0.0, own_vrf=False)
ROWS = [
    ("reference: Base settings, 2 % fee", (350, 50, 300), None, 0.0175, 200),
    ("lean: at cost, margin to GRAIL", (0, 10, 90), 0, 0.0275, 300),
    ("1 % below cost", (0, 10, 90), -100, 0.0275, 300),
    ("2.5 % below cost", (0, 10, 90), -250, 0.0275, 300),
]
GAS_PER_PULL = 0.00002


def main():
    seeds = int(sys.argv[1]) if len(sys.argv) > 1 else 200
    lines = ["# FWA custom pool: best player outcome (generated by sim/fwa_best.py)\n",
             f"Medians over {seeds} seeds; see the module docstring. ETH unless marked.\n",
             "| trading ETH/day | config | price/pull | return | GRAILs | hours w/o GRAIL | GRAIL from trading | NAV change "
             "| backstop | p(restock short) | keeper unpaid | you (0.25 % of trading) | mint fees | farm pulls/day |",
             "|" + "---|" * 14]
    for vol in (1.0, 3.0, 10.0):
        for name, split, markup, treasury, fee_bps in ROWS:
            plat = dict(FWA, treasury_rate=treasury)
            if markup is not None:
                plat["markup_bps"] = markup
            cfg = (name, *split, 2500, True, True)
            r = run(cfg, 300, vol, 0.05, seeds, platform=plat)
            n = max(r["pulls"], 1)
            price = r["paid"] / n
            farming.LOSS = price - (r["won"] - r["won_grail"]) / n + GAS_PER_PULL
            farm = farming.run(25e6, 0.7, fee_bps=fee_bps)["pulls_total"] / 14
            lines.append(f"| {vol:g} | {name} | {price:.5f} | {100 * r['rtp_total']:.1f} % | {r['grails']:.0f} | "
                         f"{r['no_grail_h']:.0f} | {r['grail_trading']:.3f} | {r['nav'] - 2.2:+.3f} | {r['backstopped']:.3f} | "
                         f"{100 * r['p_shortfall']:.0f} % | {r['keeper_unpaid_mean']:.4f} | {vol * 14 * 0.0025:.3f} | "
                         f"{r['mint_fees']:.2f} | {farm:.0f} |")
            print(lines[-1], flush=True)
    out = os.path.join(os.path.dirname(__file__), "results", "fwa-best.md")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
