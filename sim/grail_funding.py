#!/usr/bin/env python3
"""Less pull ETH to the GRAIL, more trading fees to it: Base and FWA (with our settlement fee) side by side.

Fee mixes, all with premium 3.5 % and maintenance 0.5 % of backing:
  - current: GRAIL feed 3 % of backing, ENGINE trading fee 2 % (treasury 1.75 %, operator 0.25 %)
  - feed 1 %, trading fee 3 % (treasury 2.75 %, operator 0.25 %)
  - feed 0 %, trading fee 3 %: the GRAIL is funded by trading fees only
The 14-day model is sim/followup.py (Base launch settings, see sim/fwa_compare.py for the platforms).
Trading volume is the same at 2 % and 3 %, which flatters 3 %: a higher fee moves some trades to rival
pools (test/unit/Bypass.t.sol). `farm pulls/day` is the genesis equilibrium of sim/farming.py (25M
allocation, 0.7 ETH/day of outside buying, farmers sell everything) at that mix's loss per pull and fee.
Writes sim/results/grail-funding.md. Usage: python3 sim/grail_funding.py [seeds]
"""
import os, sys

sys.path.insert(0, os.path.dirname(__file__))
import farming  # noqa: E402
from followup import run  # noqa: E402

MIXES = [("current: feed 3 %, fee 2 %", 300, 200), ("feed 1 %, fee 3 %", 100, 300), ("feed 0 %, fee 3 %", 0, 300)]
PLATFORMS = [("Base", dict(name="base", edge=0.0, settle=0.01, own_vrf=True), 0.01),
             ("FWA + our fee", dict(name="fwa+fee", edge=0.05, settle=0.01, own_vrf=False), 0.05)]
OPERATOR = 0.0025
VRF_MARGIN_PER_PULL = 1_250_000 * 0.01e-9 * 0.3
GAS_PER_PULL = 0.00002


def main():
    seeds = int(sys.argv[1]) if len(sys.argv) > 1 else 200
    lines = ["# GRAIL funding: pull feed vs. trading fees (generated by sim/grail_funding.py)\n",
             f"Medians over {seeds} seeds, 14 days, 300 pulls/day. `return` = ETH in prizes won / ETH paid, GRAIL wins "
             "included. `loss/pull` = price - expected prize + wallet gas. `You` = settlement share + VRF margin "
             "(Base) + 0.25 % of trading. ETH unless marked.\n",
             "| trading ETH/day | platform | mix | price/pull | return | loss/pull | GRAILs | hours w/o GRAIL | GRAIL from pulls "
             "| GRAIL from trading | buyback budget | you | farm pulls/day |", "|" + "---|" * 13]
    for vol in (1.0, 3.0, 10.0):
        for pname, plat, gas in PLATFORMS:
            for mname, feed, fee_bps in MIXES:
                cfg = (mname, 350, 50, feed, 2500, True, True)
                p = dict(plat, treasury_rate=(fee_bps - 25) / 10_000)
                r = run(cfg, 300, vol, gas, seeds, platform=p)
                n = max(r["pulls"], 1)
                price = r["paid"] / n
                loss = price - r["won"] / n + GAS_PER_PULL
                ordinary_loss = price - (r["won"] - r["won_grail"]) / n + GAS_PER_PULL
                farming.LOSS = ordinary_loss
                farm = farming.run(25e6, 0.7, fee_bps=fee_bps)["pulls_total"] / 14
                you = r["settle_take"] * 0.25 + (n * VRF_MARGIN_PER_PULL if pname == "Base" else 0) + vol * 14 * OPERATOR
                lines.append(f"| {vol:g} | {pname} | {mname} | {price:.5f} | {100 * r['rtp_total']:.1f} % | {loss:.5f} | "
                             f"{r['grails']:.0f} | {r['no_grail_h']:.0f} | {r['feed']:.3f} | {r['grail_trading']:.3f} | "
                             f"{r['buyback']:.3f} | {you:.3f} | {farm:.0f} |")
                print(lines[-1], flush=True)
    out = os.path.join(os.path.dirname(__file__), "results", "grail-funding.md")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
