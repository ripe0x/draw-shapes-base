#!/usr/bin/env python3
"""Generate the Base-blue presentation contracts from the pinned Shapes v1 / Draw Packs sources.

Only colours change: the card is a white field with Base-blue (#0052FF) marks; the inverted
(Black Shape) card is a Base-blue field with white marks; collection and pack preview cards are white. Token, backing, mint, compose and redemption logic are untouched (they live in Shapes.sol /
ShapePacks.sol, which are deployed unchanged). Every substitution must match exactly once.
Run from the repo root: python3 script/presentation/make_base_renderers.py
"""
import re, pathlib

BLUE = "#0052FF"
HEADER = ("// Generated by script/presentation/make_base_renderers.py from {src} at the pinned submodule\n"
          "// commit. Only the colour literals listed in that script differ from the original. Do not edit.\n")

JOBS = [
    ("lib/shapes/src/ShapeRenderer.sol", "src/presentation/BaseShapeRenderer.sol",
     [('contract ShapeRenderer is', 'contract BaseShapeRenderer is'),
      ('string memory bg = inverted ? "#fff" : "#000";', f'string memory bg = inverted ? "{BLUE}" : "#fff";'),
      ('string memory fg = inverted ? "#000" : "#fff";', f'string memory fg = inverted ? "#fff" : "{BLUE}";')]),
    ("lib/shapes/src/ShapeCollection.sol", "src/presentation/BaseShapeCollection.sol",
     [('contract ShapeCollection is', 'contract BaseShapeCollection is'),
      ('rx="40" fill="#000" filter="url(#d)"', f'rx="40" fill="#fff" filter="url(#d)"')]),
    ("lib/draw-packs/src/ShapePackRenderer.sol", "src/presentation/BasePackRenderer.sol",
     [('contract ShapePackRenderer is', 'contract BasePackRenderer is'),
      ('\'" fill="#000" filter="url(#d)"/><svg width="\'', f'\'" fill="#fff" filter="url(#d)"/><svg width="\'')]),
]

def fix_imports(text, pkg):
    # relative imports of the original file become package imports
    return re.sub(r'from "\./', f'from "{pkg}/', text)

for src, dst, subs in JOBS:
    text = pathlib.Path(src).read_text()
    for old, new in subs:
        n = text.count(old)
        assert n == 1, f"{src}: expected one match of {old!r}, found {n}"
        text = text.replace(old, new)
    pkg = "shapes" if "lib/shapes" in src else "draw-packs"
    text = fix_imports(text, pkg)
    lines = text.split("\n", 1)
    text = lines[0] + "\n" + HEADER.format(src=src) + lines[1]
    pathlib.Path(dst).write_text(text)
    print("wrote", dst)
